// 1. Kiểu dữ liệu chuỗi (String)
let tenHocVien = "An";
let thongDiep = "Chào mừng đến với 30DaysOfJavaScript";

// 2. Kiểu dữ liệu Boolean (true hoặc false)
let dangHocJavaScript = true;
let daHoanThanhKhoaHoc = false;

// 3. Kiểu dữ liệu Undefined (Biến được khai báo nhưng chưa gán giá trị)
let ghiChuChuaDinhDanh;

// 4. Kiểu dữ liệu Null (Biến đại diện cho một giá trị rỗng hoặc không có giá trị cố ý)
let ketQuaKiemTra = null;

// Kiểm tra kiểu dữ liệu của các biến (bạn có thể xem ở Console)
console.log(typeof tenHocVien);         // string
console.log(typeof dangHocJavaScript);  // boolean
console.log(typeof ghiChuChuaDinhDanh); // undefined
console.log(typeof ketQuaKiemTra);      // object (lịch sử đặc thù của JavaScript)
